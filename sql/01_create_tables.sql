-- Schéma relationnel pour le projet « Analyse des ventes avec SQL ».
-- À exécuter dans une base PostgreSQL dédiée au projet.

CREATE TABLE IF NOT EXISTS customers (
    customer_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    first_name text NOT NULL CHECK (btrim(first_name) <> ''),
    last_name text NOT NULL CHECK (btrim(last_name) <> ''),
    email text NOT NULL UNIQUE CHECK (btrim(email) <> ''),
    created_at timestamp without time zone NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS products (
    product_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_name text NOT NULL UNIQUE CHECK (btrim(product_name) <> ''),
    category text NOT NULL CHECK (btrim(category) <> ''),
    unit_price numeric(10, 2) NOT NULL CHECK (unit_price > 0),
    is_active boolean NOT NULL DEFAULT true
);

CREATE TABLE IF NOT EXISTS orders (
    order_id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id bigint NOT NULL REFERENCES customers (customer_id),
    order_date timestamp without time zone NOT NULL,
    order_status text NOT NULL
        CHECK (order_status IN ('completed', 'pending', 'cancelled'))
);

CREATE TABLE IF NOT EXISTS order_items (
    order_id bigint NOT NULL REFERENCES orders (order_id) ON DELETE CASCADE,
    product_id bigint NOT NULL REFERENCES products (product_id),
    quantity integer NOT NULL CHECK (quantity > 0),
    unit_price numeric(10, 2) NOT NULL CHECK (unit_price >= 0),
    PRIMARY KEY (order_id, product_id)
);

CREATE INDEX IF NOT EXISTS idx_orders_customer_id
    ON orders (customer_id);
CREATE INDEX IF NOT EXISTS idx_orders_order_date
    ON orders (order_date);
CREATE INDEX IF NOT EXISTS idx_order_items_product_id
    ON order_items (product_id);
